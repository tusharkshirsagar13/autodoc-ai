"""Potential inconsistency and completeness findings with a human review workflow."""

from __future__ import annotations

from collections import Counter

import streamlit as st

from config.settings import get_settings
from src.ai.llm_provider import llm_status
from src.analysis.consistency_checker import RULES, SEVERITIES
from src.database import repository as repo
from src.database.models import FINDING_REVIEW_STATUSES
from src.exports.csv_exporter import findings_csv
from src.services import audit_service, document_service
from src.ui.components import (badge, context_bar, empty_state, esc, evidence_block, metric_card, page_header,
                               require_active_revision, show_error)
from src.utils.errors import AutoDocError

settings = get_settings()
page_header("Findings & Review", "Potential inconsistencies and gaps detected by transparent rules. "
                                 "Findings support a human review — they do not establish compliance or correctness.")
revision = require_active_revision()
if not revision:
    st.stop()
context_bar(revision)
rid = revision["id"]
status = llm_status(settings)

b1, b2, b3 = st.columns([1.2, 1.2, 3])
if b1.button("Run checks", icon=":material/rule:", width="stretch",
             help="Re-runs extraction and all deterministic rules. Review decisions are kept."):
    with st.spinner("Running checks…"):
        try:
            stats = document_service.rerun_extraction(settings, rid)
            f = stats["findings"]
            st.toast(f"{f['new']} new · {f['unchanged']} unchanged · {f['resolved']} no longer reproduced")
        except Exception as exc:
            show_error(exc)
if b2.button("AI review", icon=":material/auto_awesome:", width="stretch", disabled=not status["configured"],
             help="Asks the language model for additional observations. They are stored as 'AI suggestion' (Info) "
                  "and must be verified."):
    with st.spinner("Requesting AI observations…"):
        try:
            stats = document_service.run_ai_review(settings, rid)
            st.toast(f"{stats['new']} AI suggestion(s) added.")
        except AutoDocError as exc:
            st.error(exc.user_message(), icon=":material/error:")
if not status["configured"]:
    b3.caption("AI review requires a configured language model. All deterministic checks work without one.")
elif status["external"]:
    b3.caption(f"AI review sends the extracted inventory (names, descriptions, pages) to {status['destination']}.")

findings = repo.list_findings(rid, settings=settings)
if not findings:
    empty_state("No findings", "No potential issues were detected by the enabled rules for this revision.")
    st.stop()

sev = Counter(f["severity"] for f in findings if f["review_status"] == "open")
cols = st.columns(5)
for col, s in zip(cols, SEVERITIES):
    with col:
        metric_card(f"{s} · open", sev.get(s, 0))
with cols[4]:
    metric_card("Reviewed", sum(1 for f in findings if f["review_status"] != "open"), f"of {len(findings)}")

with st.expander("How to read findings", icon=":material/help:"):
    st.markdown("""
- **Observed** — the issue is directly visible in the extracted data (e.g. two components share an ID).
- **Missing evidence** — something referenced could not be found in the *extracted* inventory. It may be defined in another
  document, a diagram, or a table the parser did not recognise. It is **not** a confirmed defect.
- **Extraction coverage** — part of the document could not be read reliably and needs manual review.
- **AI suggestion** — generated by the language model; treat as a prompt for human verification only.
""")
    st.dataframe([{"Rule": r.rule_id, "Category": r.category, "Severity": r.severity, "Evidence kind": r.evidence_kind,
                   "Description": r.description} for r in RULES.values()], hide_index=True, width="stretch")

f1, f2, f3, f4 = st.columns(4)
sel_sev = f1.multiselect("Severity", SEVERITIES, default=SEVERITIES)
cats = sorted({f["category"] for f in findings})
sel_cat = f2.multiselect("Category", cats, default=cats)
sel_status = f3.multiselect("Review status", FINDING_REVIEW_STATUSES, default=FINDING_REVIEW_STATUSES)
source = f4.selectbox("Source", ["All", "Deterministic rules", "AI suggestions"])
shown = [f for f in findings if f["severity"] in sel_sev and f["category"] in sel_cat and f["review_status"] in sel_status
         and (source == "All" or (source == "AI suggestions") == bool(f["is_ai_generated"]))]
st.caption(f"Showing {len(shown)} of {len(findings)} findings.")
st.download_button("Export findings (CSV)", findings_csv(shown), file_name=f"autodoc_findings_{revision['revision_label']}.csv",
                   mime="text/csv", icon=":material/download:", disabled=not shown)

STATUS_LABELS = {"open": "Open", "accepted": "Accepted (valid issue)", "rejected": "Rejected (not an issue)",
                 "needs_investigation": "Needs further investigation"}
for f in shown:
    kind_label = "AI suggestion" if f["is_ai_generated"] else f["evidence_kind"].replace("_", " ")
    title = f"{f['code']} · {f['severity']} · {f['summary']}"
    with st.expander(title):
        st.markdown(f"{badge(f['severity'])} {badge(f['review_status'])} {badge('grey', kind_label)} "
                    f"<span class='ad-muted'>{esc(f['category'])} · detected by {esc(f['detection_method'])} · "
                    f"pages {', '.join(map(str, f['pages'])) or '—'}</span>", unsafe_allow_html=True)
        st.markdown(f["explanation"])
        if f["evidence"]:
            st.markdown("**Supporting evidence**")
            evidence_block(f["evidence"])
        with st.form(f"fr_{f['id']}"):
            c1, c2 = st.columns([1, 2])
            decision = c1.selectbox("Review decision", FINDING_REVIEW_STATUSES,
                                    index=FINDING_REVIEW_STATUSES.index(f["review_status"]),
                                    format_func=lambda s: STATUS_LABELS[s])
            comment = c2.text_input("Reviewer comment", f["reviewer_comment"])
            reviewer = st.text_input("Reviewer name", value=st.session_state.get("reviewer_name", ""))
            if st.form_submit_button("Save review", type="primary"):
                repo.review_finding(f["id"], decision, comment, reviewer, settings=settings)
                st.session_state["reviewer_name"] = reviewer
                audit_service.record("finding_reviewed", "finding", f["id"], settings=settings, decision=decision, code=f["code"])
                st.toast(f"{f['code']} marked as {STATUS_LABELS[decision].lower()}.")
                st.rerun()

with st.expander("Review history", icon=":material/history:"):
    decisions = repo.list_review_decisions(rid, settings=settings)
    if decisions:
        st.dataframe([{"When": d["created_at"], "Target": d["target_type"], "Decision": d["decision"],
                       "Reviewer": d["reviewer"], "Comment": d["comment"]} for d in decisions], hide_index=True, width="stretch")
    else:
        st.caption("No review decisions recorded yet.")
